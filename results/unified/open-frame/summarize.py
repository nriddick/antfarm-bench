"""Summarize a pass from its recorded evidence only. Usage: python3 -B summarize.py WAVE
Writes WAVE/SUMMARY.json and WAVE/SUMMARY.md. Timings are the parent's split-smt high-count
evaluation (eval-adapt) medians of fresh plain processes: native run() ms at the fixed cell
updates and median complete-frame ms for the composite recipes; opaque-C is descriptive.
'adapt' is the late-stage source, 'selected' the version it started from.
"""
import json,statistics,sys
from pathlib import Path
HERE=Path(__file__).resolve().parent
NS=(8,15,24,30,32,40)

def load(p):
    try:return json.loads(Path(p).read_text())
    except (OSError,ValueError):return None

def med(xs):
    xs=[x for x in xs if x];return statistics.median(xs) if xs else None

def main(wave):
    out=HERE/wave;rows=[]
    for t in sorted(p for p in out.iterdir() if p.is_dir()):
        r={'trajectory':t.name,'stages':{},'gates':{},'selection':None}
        for s in ('initial','opt1','adapt'):
            p=load(t/s/'PROCESS.json')
            if p and 'commit' in p:r['stages'][s]={'minutes':round(p['wall_seconds']/60,1),'turns':(p.get('result') or {}).get('num_turns'),'inputs_ok':p.get('protected_inputs_unchanged'),
                                 'tests':p.get('test_runs'),'interrupted':'interruption' in p,'error':(p.get('result') or {}).get('is_error')}
        for g in ('opt1','adapt'):
            x=load(t/f'gate-{g}'/'GATE.json')
            if x:r['gates'][g]={'native':x['native'],'frame':x['frame']}
        sel=load(t/'eval-opt1'/'SELECTION.json')
        if sel:r['selection']={'decision':sel['decision'],'native':sel['native']['geomean_ratio'],'composite':sel['frame']['geomean_ratio'],'joint':sel['joint']}
        rep=(t/'reviewer-sonnet-medium'/'REPORT.md')
        if rep.exists():
            line=next((l for l in rep.read_text().splitlines() if 'isposition' in l),'')
            r['review']=line.replace('*','').split(':',1)[-1].strip().split('.')[0]
        ev=load(t/'eval-adapt'/'processes.json') or []
        times={}
        for p in ev:
            if p['variant']!='plain':continue
            times.setdefault((p['label'],p['kind'],str(p['what']),p['workers']),[]).append(p.get('value_ns') if p['passed'] else None)
        r['eval_adapt']={f'{l}|{k}|{w}|{n}':(med(v),sum(x is None for x in v)) for (l,k,w,n),v in times.items()}
        disp=load(t/'eval-adapt'/'DISPOSITION.json')
        if disp:r['disposition']={'all_correct':disp['all_correct'],'geomean':disp['geomean'],'regressions':[(x['what'],x['workers'],round(x['geomean_ratio'],3)) for x in disp.get('regressions_over_1_5pct',[])]}
        rows.append(r)
    (out/'SUMMARY.json').write_text(json.dumps(rows,indent=1)+'\n')
    md=[f'# {wave} summary (generated by summarize.py from recorded evidence)','',
        '## Stages','','| Trajectory | initial min | opt1 min | adapt min | inputs ok | gates opt1 / adapt (N,F) | opt1 retained (native, composite) | review |','|---|---|---|---|---|---|---|---|']
    yn=lambda b:'P' if b else 'F'
    for r in rows:
        s=r['stages'];g=r['gates'];sel=r['selection']
        md.append(f"| {r['trajectory']} | {s.get('initial',{}).get('minutes','-')} | {s.get('opt1',{}).get('minutes','-')} | {s.get('adapt',{}).get('minutes','-')}"
                  f" | {all(v.get('inputs_ok') for v in s.values()) if s else '-'}"
                  f" | {'/'.join(yn(g[x]['native'])+yn(g[x]['frame']) for x in ('opt1','adapt') if x in g) or '-'}"
                  f" | {('%s %.3f, %s %.3f' % (yn(sel['decision']['native']),sel['native'],yn(sel['decision']['frame']),sel['composite'])) if sel else '-'}"
                  f" | {r.get('review','-')} |")
    def table(title,kind,whats,unit,div):
        md.extend(['',f'## {title}','',f'Median of fresh plain processes, {unit}; adapted source (selected in brackets when it differs or failed). F = no passing process.','',
                   '| Trajectory | '+' | '.join(f'{w} N={n}' for w in whats for n in NS)+' |','|---|'+'---|'*(len(whats)*len(NS))])
        for r in rows:
            e=r['eval_adapt'];cells=[]
            for w in whats:
                for n in NS:
                    a=e.get(f'adapt|{kind}|{w}|{n}');s=e.get(f'selected|{kind}|{w}|{n}')
                    fa='F' if not a or a[0] is None else f'{a[0]/div:.3g}'
                    fs='' if not s else (' [F]' if s[0] is None else '')
                    cells.append(fa+fs)
            md.append(f"| {r['trajectory']} | "+' | '.join(cells)+' |')
    table('Native GoL run time','native',('64','256','1024'),'ms',1e6)
    table('Composite frame latency','frame',('frame-gol-small','frame-gol-heavy'),'ms',1e6)
    table('Standalone opaque-C GoL (descriptive, one pair)','frame',('gol-c-64','gol-c-256','gol-c-1024'),'ms',1e6)
    (out/'SUMMARY.md').write_text('\n'.join(md)+'\n');print(out/'SUMMARY.md')

if __name__=='__main__':main(sys.argv[1])
